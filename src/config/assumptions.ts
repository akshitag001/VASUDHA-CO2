// Rules:
// - Nothing numeric that drives a result may be hardcoded anywhere else.
// - Every entry carries value, unit, low/high range, source, year and confidence.
// - `verified: false` means the team has not yet checked the value against the
//   cited source. The UI shows those with a "VERIFY" flag. Do not flip it to
//   true without checking the source yourself.

